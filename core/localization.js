export function translateEnglish(value) {
  const text = String(value);
  return ENGLISH_EXACT.get(text) ?? ENGLISH_LINES.get(text) ?? translateDynamic(text);
}

export function localizeEvent(event, language) {
  if (normalizeLanguage(language) !== LANGUAGE.en) return event;
  return {
    ...event,
    title: translateEnglish(event.title),
    lines: Array.isArray(event.lines) ? event.lines.map(translateEnglish) : [],
  };
}
