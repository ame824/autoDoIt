export function normalizeLanguage(value) {
  return String(value).trim().toLowerCase() === LANGUAGE.en ? LANGUAGE.en : LANGUAGE.de;
}

export function readLanguage(ns) {
  return normalizeLanguage(ns.read(LANGUAGE_FILE));
}

export function writeLanguage(ns, language) {
  const normalized = normalizeLanguage(language);
  ns.write(LANGUAGE_FILE, normalized, "w");
  return normalized;
}

export function dashboardText(language, key, values = {}) {
  const normalized = normalizeLanguage(language);
  let text = DASHBOARD_TEXT[normalized]?.[key] ?? DASHBOARD_TEXT.de[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

